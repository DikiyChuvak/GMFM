function SPeditor.L(key)
	if not CLIENT then return key end
	local lang = GetConVarString("speditor_language") or "en"
	local t = SPeditor.Lang[lang] or SPeditor.Lang.en
	return t[key] or SPeditor.Lang.en[key] or key
end

-- Translating a name that comes from data (a light preset, a bone group, an attribute name…): the key
-- is built from a prefix and the name ("Soft white" -> preset_soft_white). If the
-- dictionary has no such key, the name is shown as is.
function SPeditor.LN(prefix, name)
	if not CLIENT or not isstring(name) then return name end
	local key = prefix .. string.Trim(string.gsub(string.lower(name), "[^%w]+", "_"), "_")
	local str = SPeditor.L(key)
	if str == key then return name end
	return str
end
